import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
mkdirSync('.codex/city-qa', { recursive: true });
const browser = await chromium.launch();
try {
  for (const width of [1440, 375]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, reducedMotion: 'reduce', isMobile: width === 375, hasTouch: width === 375 });
    const page = await context.newPage();
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto('http://127.0.0.1:4321/projetos/entrevias/', { waitUntil: 'networkidle' });
    await page.addStyleTag({ content: 'astro-dev-toolbar{display:none!important}' });
    await page.waitForSelector('[data-tour][open]');
    await page.screenshot({ path: `.codex/city-qa/tour-${width}-welcome.png` });
    assert.match(await page.locator('#tour-title').textContent(), /futuro desta cidade/);
    await page.locator('[data-tour-next]').click();
    assert.equal(await page.locator('#demand').inputValue(), '95');
    assert.equal(await page.locator('#transit').inputValue(), '10');
    await page.screenshot({ path: `.codex/city-qa/tour-${width}-demo.png` });
    const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
    assert.deepEqual(axe.violations.map(v => ({ id: v.id, targets: v.nodes.map(n => n.target) })), []);
    await page.locator('[data-tour-next]').click();
    assert.equal(await page.locator('#transit').inputValue(), '65');
    assert.equal(await page.locator('#bus-lane').isChecked(), true);
    await page.locator('[data-tour-next]').click();
    assert.equal(await page.locator('#signal').inputValue(), '6');
    await page.locator('[data-tour-next]').click();
    assert.equal(await page.locator('#works').isChecked(), true);
    await page.locator('[data-tour-back]').click();
    assert.equal(await page.locator('#works').isChecked(), false);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('[data-tour]').isVisible(), false);
    assert.equal(await page.locator('#demand').inputValue(), '55');
    assert.equal(await page.locator('#transit').inputValue(), '25');
    assert.equal(await page.locator('[data-clock]').textContent(), '00:12');
    await page.locator('[data-tour-open]').click();
    await page.locator('[data-tour-skip]').click();
    await page.reload({ waitUntil: 'networkidle' });
    assert.equal(await page.locator('[data-tour]').isVisible(), false);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.deepEqual(errors, []);
    console.log(`${width}px: introdução automática, etapas, dados reais, voltar, Escape, restauração, repetição, sessão e acessibilidade OK`);
    if (width === 1440) {
      await page.locator('[data-challenge-open]').click();
      await page.waitForFunction(() => !document.querySelector('[data-challenge-test]').disabled, null, { timeout: 120000 });
      assert.equal(await page.locator('[data-challenge-progress]').getAttribute('value'), '120');
      assert.equal(await page.locator('#demand').isDisabled(), true);
      assert.equal(await page.locator('#demand').inputValue(), '95');
      assert.equal(await page.locator('[data-ref=completed]').textContent(), '281');
      await page.locator('#transit').fill('65');
      await page.locator('#signal').fill('12');
      await page.locator('#bus-lane').check();
      await page.locator('[data-challenge-test]').click();
      await page.waitForFunction(() => document.querySelector('[data-challenge-status]').textContent.startsWith('Desafio concluído'), null, { timeout: 120000 });
      assert.equal(await page.locator('[data-solution=completed]').textContent(), '407');
      await page.locator('[data-challenge]').screenshot({ path: '.codex/city-qa/challenge-result.png' });
      await page.locator('[data-challenge-stop]').click();
      assert.equal(await page.locator('#demand').isDisabled(), false);
      assert.equal(await page.locator('#demand').inputValue(), '55');
      await page.locator('[data-challenge-open]').click();
      await page.locator('[data-challenge-stop]').click();
      await page.waitForTimeout(100);
      assert.equal(await page.locator('#demand').inputValue(), '55');
      console.log('Desafio: referência e tentativa com 120 s, demanda fixa, resultado reproduzível e cancelamento sem alterações tardias OK');
    }
    await context.close();
  }
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  await page.goto('http://127.0.0.1:4321/projetos/entrevias/', { waitUntil: 'networkidle' });
  await page.locator('[data-tour-next]').click();
  await page.waitForTimeout(1400);
  await page.locator('[data-tour-auto]').click();
  assert.equal(await page.locator('#demand').inputValue(), '95');
  const clock = await page.locator('[data-clock]').textContent();
  await page.waitForTimeout(300);
  assert.equal(await page.locator('[data-clock]').textContent(), clock);
  await page.locator('[data-tour-auto]').click();
  await page.waitForFunction(previous => document.querySelector('[data-clock]').textContent !== previous, clock);
  await page.locator('[data-tour-skip]').click();
  console.log('Movimento normal: animação altera os controles, pausa e retoma a demonstração');
  await context.close();
} finally { await browser.close(); }
